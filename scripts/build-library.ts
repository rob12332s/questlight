/**
 * Generates the GCSE library migration from src/content/library and src/content/lessons.
 *
 *   npx tsx scripts/build-library.ts
 *
 * Topic ids are derived from subject/slug, so re-running produces the same ids. The
 * migration is idempotent: topics are upserted (a verification set by a content admin is
 * never downgraded), and a lesson's version only goes up when its content changed.
 * The build stops if the catalogue or any lesson fails validation.
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { QUESTION_BANK } from "../src/content/bank";
import { LIBRARY_ENTRIES, validateLibrary } from "../src/content/library";
import { LESSONS } from "../src/content/lessons";
import { validateLesson } from "../src/domain/lesson";

const OUT = join(process.cwd(), "supabase", "migrations", "20261202001200_library_content.sql");

export function stableUuid(name: string): string {
  const h = createHash("sha1").update(`questlight:${name}`).digest("hex");
  const variant = ((parseInt(h.slice(16, 18), 16) & 0x3f) | 0x80).toString(16).padStart(2, "0");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${variant}${h.slice(18, 20)}-${h.slice(20, 32)}`;
}

const lit = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const arr = (v: string[]) => (v.length ? `array[${v.map(lit).join(", ")}]::text[]` : "'{}'::text[]");

const quizTopics = new Set(QUESTION_BANK.map((t) => `${t.subject}/${t.slug}`));
const problems = validateLibrary(LIBRARY_ENTRIES, quizTopics);
for (const [subject, lessons] of Object.entries(LESSONS)) {
  for (const [slug, lesson] of Object.entries(lessons)) {
    if (!LIBRARY_ENTRIES.some((e) => e.subject === subject && e.slug === slug)) problems.push(`lesson ${subject}/${slug}: no library topic`);
    for (const p of validateLesson(JSON.parse(JSON.stringify(lesson)))) problems.push(`lesson ${subject}/${slug}: ${p}`);
  }
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const lines = [
  "-- ════════════════════════════════════════════════════════════════════════════",
  "-- Questlight · 0012 · GCSE library catalogue and Exam Answer Coach lessons",
  "-- GENERATED by scripts/build-library.ts — do not edit by hand.",
  "-- ════════════════════════════════════════════════════════════════════════════",
  "",
];

const rows = LIBRARY_ENTRIES.map((e) => {
  const id = stableUuid(`library/${e.subject}/${e.slug}`);
  const quiz = e.quiz ? `${lit(stableUuid(`topic/${e.quiz}`))}::uuid` : "null::uuid";
  return `  (${lit(id)}::uuid, ${lit(e.subject)}, ${lit(e.slug)}, ${lit(e.area)}, ${lit(e.subtopic)}, ${lit(e.title)}, ${lit(e.objective)}, ${lit(e.skill)}, ${lit(e.tier)}, ${lit(e.difficulty)}::public.difficulty, ${lit(e.paper)}, ${lit(e.coverage)}, ${lit(e.verification)}, ${arr(e.boards)}, ${lit(e.access)}, ${lit(e.qualification)}, ${lit(e.optionKey)}, ${quiz}, ${e.sortOrder})`;
});
lines.push(
  "insert into public.library_topics (id, subject_id, slug, area, subtopic, title, objective, skill, tier, difficulty, paper, coverage, verification, boards, access, qualification, option_key, quiz_topic_id, sort_order)",
  "select v.id, s.id, v.slug, v.area, v.subtopic, v.title, v.objective, v.skill, v.tier, v.difficulty, v.paper, v.coverage, v.verification, v.boards, v.access, v.qualification, v.option_key, q.id, v.sort_order",
  "from (values",
  rows.join(",\n"),
  ") as v (id, subject, slug, area, subtopic, title, objective, skill, tier, difficulty, paper, coverage, verification, boards, access, qualification, option_key, quiz_topic_id, sort_order)",
  "join public.subjects s on s.slug = v.subject",
  "left join public.topics q on q.id = v.quiz_topic_id",
  "on conflict (id) do update set area = excluded.area, subtopic = excluded.subtopic, title = excluded.title, objective = excluded.objective, skill = excluded.skill, tier = excluded.tier, difficulty = excluded.difficulty, paper = excluded.paper, coverage = excluded.coverage, boards = excluded.boards, qualification = excluded.qualification, option_key = excluded.option_key, quiz_topic_id = excluded.quiz_topic_id, sort_order = excluded.sort_order, updated_at = now(),",
  "  verification = case when public.library_topics.verification = 'verified' then 'verified' else excluded.verification end;",
);

lines.push("", "-- Lessons");
let lessonCount = 0;
for (const [subject, lessons] of Object.entries(LESSONS)) {
  for (const [slug, lesson] of Object.entries(lessons)) {
    lessonCount++;
    const id = stableUuid(`library/${subject}/${slug}`);
    lines.push(
      `insert into public.lessons (topic_id, content, status) values (${lit(id)}, ${lit(JSON.stringify(lesson))}::jsonb, 'published')\n` +
        `on conflict (topic_id) do update set content = excluded.content, status = 'published', version = public.lessons.version + 1, updated_at = now()\n` +
        `  where public.lessons.content is distinct from excluded.content;`,
    );
  }
}

lines.push(
  "",
  "-- What each topic offers right now: a full lesson, quiz practice, or planned.",
  "update public.library_topics t set content_status = case",
  "  when exists (select 1 from public.lessons l where l.topic_id = t.id and l.status = 'published') then 'lesson'",
  "  when t.quiz_topic_id is not null then 'practice'",
  "  else 'planned' end;",
  "",
);

writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${LIBRARY_ENTRIES.length} topics and ${lessonCount} lessons to ${OUT}`);
