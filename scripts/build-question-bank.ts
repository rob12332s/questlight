/**
 * Generates the question-bank migration from src/content/bank.
 *
 *   npx tsx scripts/build-question-bank.ts
 *
 * Ids are derived from subject/topic/key, so re-running produces the same ids and the
 * migration is idempotent (`on conflict do nothing` / `do update`). Never change a
 * question's meaning under an existing key — add a new key instead.
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { QUESTION_BANK } from "../src/content/bank";
import type { BankQuestion } from "../src/content/bank";

const OUT = join(process.cwd(), "supabase", "migrations", "20261124000400_question_bank.sql");
const OPTION_IDS = ["A", "B", "C", "D"] as const;

function stableUuid(name: string): string {
  const h = createHash("sha1").update(`questlight:${name}`).digest("hex");
  // Format as an RFC 4122 version-5 style UUID.
  const variant = ((parseInt(h.slice(16, 18), 16) & 0x3f) | 0x80).toString(16).padStart(2, "0");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${variant}${h.slice(18, 20)}-${h.slice(20, 32)}`;
}

const lit = (value: string) => `'${value.replace(/'/g, "''")}'`;
const json = (value: unknown) => `${lit(JSON.stringify(value))}::jsonb`;

function optionsFor(q: BankQuestion): unknown {
  if (q.type === "mc") return q.options.map((text, i) => ({ id: OPTION_IDS[i], text }));
  if (q.type === "tf") return [{ id: "A", text: "True" }, { id: "B", text: "False" }];
  return null;
}

const lines: string[] = [
  "-- ════════════════════════════════════════════════════════════════════════════",
  "-- Questlight · 0004 · Original GCSE question bank",
  "-- GENERATED by scripts/build-question-bank.ts from src/content/bank — do not edit.",
  "-- All questions are written for Questlight. No exam-board labels are applied.",
  "-- ════════════════════════════════════════════════════════════════════════════",
  "",
];

let topicCount = 0;
let questionCount = 0;

QUESTION_BANK.forEach((topic, topicIndex) => {
  const topicId = stableUuid(`topic/${topic.subject}/${topic.slug}`);
  topicCount += 1;
  lines.push(`-- ${topic.subject} / ${topic.name}`);
  lines.push(
    `insert into public.topics (id, subject_id, slug, name, description, education_stage, sort_order)\n` +
      `select ${lit(topicId)}, id, ${lit(topic.slug)}, ${lit(topic.name)}, ${lit(topic.description)}, 'gcse', ${(topicIndex + 1) * 10}\n` +
      `from public.subjects where slug = ${lit(topic.subject)}\n` +
      `on conflict (id) do update set name = excluded.name, description = excluded.description;`,
  );

  for (const q of topic.questions) {
    const id = stableUuid(`question/${topic.subject}/${topic.slug}/${q.key}`);
    questionCount += 1;
    const type = q.type === "mc" ? "multiple_choice" : q.type === "tf" ? "true_false" : "short_answer";
    const options = optionsFor(q);
    lines.push(
      `insert into public.questions (id, topic_id, question_type, question_text, options, difficulty, source_type, is_published) values ` +
        `(${lit(id)}, ${lit(topicId)}, '${type}', ${lit(q.q)}, ${options === null ? "null" : json(options)}, '${q.difficulty}', 'question_bank', true)\n` +
        `on conflict (id) do update set question_text = excluded.question_text, options = excluded.options, difficulty = excluded.difficulty;`,
    );
    if (q.type === "short") {
      const accepted = `array[${q.accept.map(lit).join(", ")}]::text[]`;
      lines.push(
        `insert into public.question_answers (question_id, accepted_answers, explanation) values (${lit(id)}, ${accepted}, ${lit(q.explain)})\n` +
          `on conflict (question_id) do update set accepted_answers = excluded.accepted_answers, explanation = excluded.explanation;`,
      );
    } else {
      const correct = q.type === "mc" ? OPTION_IDS[q.answer] : q.answer ? "A" : "B";
      lines.push(
        `insert into public.question_answers (question_id, correct_option, explanation) values (${lit(id)}, '${correct}', ${lit(q.explain)})\n` +
          `on conflict (question_id) do update set correct_option = excluded.correct_option, explanation = excluded.explanation;`,
      );
    }
  }
  lines.push("");
});

writeFileSync(OUT, `${lines.join("\n")}\n`);
console.log(`Wrote ${topicCount} topics and ${questionCount} questions to ${OUT}`);
